const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  spawn: (opts) => ipcRenderer.invoke('pty:spawn', opts),
  listSessions: () => ipcRenderer.invoke('sessions:list'),
  pickFolder: (start) => ipcRenderer.invoke('dialog:folder', start),
  onConfirmClose: (cb) => ipcRenderer.on('app:confirm-close', (_, running) => cb(running)),
  closeApp: () => ipcRenderer.send('app:close'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  openUpdate: (url) => ipcRenderer.send('update:open', url),
  onUpdateReady: (cb) => ipcRenderer.on('update:ready', (_, v) => cb(v)),
  onUpdateManual: (cb) => ipcRenderer.on('update:manual', (_, info) => cb(info)),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  writeKeys: (id, keys, gap) => ipcRenderer.send('pty:keys', id, keys, gap),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (cb) => ipcRenderer.on('pty:data', (_, id, data) => cb(id, data)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_, id, code) => cb(id, code)),
  onAgentEvent: (cb) => ipcRenderer.on('agent:event', (_, id, event) => cb(id, event)),
  platform: process.platform,
  getUsage: (agent) => ipcRenderer.invoke('usage:get', agent),
  detectAgents: () => ipcRenderer.invoke('agents:detect'),
  sysInfo: () => ipcRenderer.invoke('sys:info'),
  setRoster: (roster, links) => ipcRenderer.send('roster:set', roster, links),
  onCallStart: (cb) => ipcRenderer.on('call:start', (_, c) => cb(c)),
  onCallEnd: (cb) => ipcRenderer.on('call:end', (_, id) => cb(id)),
  copy: (text) => ipcRenderer.send('clipboard:write', text),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  saveImage: (bytes) => ipcRenderer.invoke('image:save', bytes),
  pathOfFile: (file) => webUtils.getPathForFile(file),
  resolveFiles: (cwd, cands) => ipcRenderer.invoke('files:resolve', cwd, cands),
  listDir: (dir) => ipcRenderer.invoke('files:list', dir),
  gitChanges: (dir) => ipcRenderer.invoke('files:status', dir),
  searchFiles: (dir, q) => ipcRenderer.invoke('files:search', dir, q),
  readFile: (file) => ipcRenderer.invoke('files:read', file),
  writeFile: (file, text, mtime, force) => ipcRenderer.invoke('files:write', file, text, mtime, force),
  fileOp: (op, root, target, name) => ipcRenderer.invoke('files:op', op, root, target, name),
  onFocusNode: (cb) => ipcRenderer.on('node:focus', (_, id) => cb(id)),
  addWorktree: (repo, branch) => ipcRenderer.invoke('git:worktree-add', repo, branch),
  stopAgent: (agentId) => ipcRenderer.send('agent:stop', agentId),
  readTranscript: (file) => ipcRenderer.invoke('agent:transcript', file),
  listPaths: (extra) => ipcRenderer.invoke('paths:list', extra),
  loadBoard: () => ipcRenderer.invoke('board:load'),
  saveBoard: (board) => ipcRenderer.send('board:save', board),
});
